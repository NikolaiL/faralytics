const fs=require('node:fs');
const path=require('node:path');
const {ethers,artifacts}=require('hardhat');
const RECIPIENT='0x8D6230427a37986D25Fe4D5B3d0aaEF1b924fEd6';
const FACTORY='0x4e59b44847b379578588920cA78FbF26c0B4956C';
async function main(){
 for(const file of ['../nextjs/.env.local','../../.env.local','.env.local'])if(fs.existsSync(file))process.loadEnvFile(file);
 const provider=ethers.provider;
 if((await provider.getNetwork()).chainId!==8453n)throw new Error('Deployment requires Base mainnet.');
 const artifact=await artifacts.readArtifact('FaralyticsIPFS');
 if((artifact.deployedBytecode.length-2)/2>24576)throw new Error('Contract exceeds runtime size limit.');
 const init=ethers.concat([artifact.bytecode,ethers.AbiCoder.defaultAbiCoder().encode(['address'],[RECIPIENT])]);
 const salt=ethers.id('faralytics.activity-ipfs.v2');
 const address=ethers.getCreate2Address(FACTORY,salt,ethers.keccak256(init));
 const recordPath="deployments/base/FaralyticsIPFS.json";
 let txHash=fs.existsSync(recordPath)?JSON.parse(fs.readFileSync(recordPath,"utf8")).transactionHash:null;
 if(await provider.getCode(address)==='0x'){
  const factoryCode=await provider.getCode(FACTORY);
  if(factoryCode!=='0x7fffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffe03601600081602082378035828234f58015156039578182fd5b8082525050506014600cf3')throw new Error('Unexpected deployment factory.');
  if(!process.env.DEPLOYER_PSWD)throw new Error('DEPLOYER_PSWD is required.');
  const wallet=(await ethers.Wallet.fromEncryptedJson(fs.readFileSync(path.resolve('.deploy-wallet.json'),'utf8'),process.env.DEPLOYER_PSWD)).connect(provider);
  const request={to:FACTORY,data:ethers.concat([salt,init]),value:0n};
  await provider.call({...request,from:wallet.address});
  const gas=await provider.estimateGas({...request,from:wallet.address});
  const fee=await provider.getFeeData();
  const maxCost=gas*(fee.maxFeePerGas||fee.gasPrice)*2n;
  if(await provider.getBalance(wallet.address)<maxCost)throw new Error('Deployer needs more Base ETH for gas.');
  console.log('Deploying on Base. Owner and fee recipient:',RECIPIENT);
  console.log('Contract:',address,'Estimated gas:',String(gas));
  const tx=await wallet.sendTransaction({...request,gasLimit:gas*12n/10n});
  txHash=tx.hash;console.log('Deployment transaction:',txHash);
  const receipt=await tx.wait(2);if(receipt.status!==1)throw new Error('Deployment reverted.');
 }
 const nft=new ethers.Contract(address,artifact.abi,provider);
 if((await nft.owner()).toLowerCase()!==RECIPIENT.toLowerCase()||(await nft.feeRecipient()).toLowerCase()!==RECIPIENT.toLowerCase()||await nft.MINT_PRICE()!==ethers.parseEther('0.001'))throw new Error('Deployment verification failed.');
 const legacy=JSON.parse(fs.readFileSync('deployments/base/FaralyticsNFT.json','utf8'));
 const output={8453:{FaralyticsNFT:{address:legacy.address,abi:legacy.abi,deployedOnBlock:legacy.deployedOnBlock||0},FaralyticsIPFS:{address,abi:artifact.abi,deployedOnBlock:0}}};
 fs.writeFileSync('../nextjs/contracts/deployedContracts.ts','// Generated by the Base deployment script.\nconst deployedContracts = '+JSON.stringify(output,null,2)+' as const;\nexport default deployedContracts;\n');
 fs.mkdirSync('deployments/base',{recursive:true});
 fs.writeFileSync('deployments/base/FaralyticsIPFS.json',JSON.stringify({address,transactionHash:txHash,owner:RECIPIENT,feeRecipient:RECIPIENT,mintPrice:'1000000000000000',abi:artifact.abi},null,2));
 console.log('Verified owner, fee recipient and mint price. Frontend contract registry updated.');
}
main().catch(()=>{console.error('Deployment failed. Check Base funding, RPC availability and the encrypted wallet/password. No secret details printed.');process.exitCode=1});
