const assert = require("node:assert/strict");
const fs = require("node:fs");
const { chromium } = require("@playwright/test");
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH });
  const errors = [];
  const context = await browser.newContext({ viewport: { width: 1280, height: 1000 }, permissions: ["clipboard-read", "clipboard-write"] });
  const page = await context.newPage();
  page.on("pageerror", e => errors.push(e.message));
  await page.addInitScript(() => { window.open = url => { window.__lastShare = url; return null; }; });
  await page.goto("http://localhost:3100/", { waitUntil: "networkidle" });
  assert.equal(await page.getByTestId("lookup-input").inputValue(), "");
  assert.equal(await page.getByTestId("activity-graph").count(), 0);
  assert.ok(await page.getByTestId("lookup-empty").isVisible());
  assert.equal(await page.getByTestId("brand-chart").locator('rect').count(), 59 * 7);
  const animatedCells = page.getByTestId("brand-chart").locator('rect');
  await animatedCells.evaluateAll(es=>es.forEach(e=>e.getAnimations().forEach(a=>{a.effect.updateTiming({delay:0});a.pause();a.currentTime=0})));
  const initialColors = await animatedCells.evaluateAll(es=>es.map(e=>getComputedStyle(e).fill));
  await animatedCells.evaluateAll(es=>es.forEach(e=>e.getAnimations().forEach(a=>{a.currentTime=Number(a.effect.getTiming().duration)/2})));
  const transitionedColors = await animatedCells.evaluateAll(es=>es.map(e=>getComputedStyle(e).fill));
  assert.ok(initialColors.every((color,i)=>color!==transitionedColors[i]), 'every letter and background cell transitions');
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await page.getByTestId("brand-chart").locator('rect').first().evaluate(e=>getComputedStyle(e).animationName), 'none');
  await page.emulateMedia({reducedMotion:'no-preference'});
  for (const id of ['copy-link', 'share-x', 'share-farcaster']) assert.equal(await page.getByTestId(id).isDisabled(), false);
  await page.getByTestId('copy-link').click();
  const appLink = new URL(await page.evaluate(() => navigator.clipboard.readText()));
  assert.equal(appLink.pathname, '/');
  assert.deepEqual([...appLink.searchParams.keys()], ['ts']);
  assert.match(appLink.searchParams.get('ts'), /^\d{13}$/);
  for (const [id, parameter] of [['share-x', 'url'], ['share-farcaster', 'embeds[]']]) {
    await page.getByTestId(id).click();
    const composer = new URL(await page.evaluate(() => window.__lastShare));
    const link = new URL(composer.searchParams.get(parameter));
    assert.equal(link.pathname, '/');
    assert.equal(link.searchParams.has('user'), false);
    assert.match(composer.searchParams.get('text'), /Look up your Farcaster activity with Faralytics/);
    assert.ok(composer.searchParams.get('text').endsWith(id==='share-x'?'faralytics - created by @NikolaiLeb with @viniapp_xyz':'faralytics - created by @nikolaii.eth with @viniapp'));
    const response = await page.request.get('http://localhost:3100/' + link.search);
    assert.equal(response.status(), 200);
    const html = await response.text();
    assert.ok(html.includes('/og/faralytics-farcaster-v12.png'));
    assert.ok(html.includes('/og/faralytics-x-v12.png'));
  }
  assert.ok((await page.locator('meta[property="og:image"]').getAttribute('content')).includes('/og/faralytics-farcaster-v12.png'));
  assert.ok((await page.locator('meta[name="twitter:image"]').getAttribute('content')).includes('/og/faralytics-x-v12.png'));
  assert.ok(JSON.parse(await page.locator('meta[name="fc:miniapp"]').getAttribute('content')).imageUrl.includes('/og/faralytics-farcaster-v12.png'));
  const initialActivity = page.waitForResponse(r => r.url().includes('/api/activity?user=366713') && r.status() === 200);
  await page.goto("http://localhost:3100/?user=366713", { waitUntil: "networkidle" });
  await page.getByTestId("activity-graph").waitFor();
  assert.equal(await page.locator('.heatmap rect').count(), 365);
  const fidData = await (await initialActivity).json();
  assert.equal(await page.getByTestId("activity-total").innerText(), fidData.total.toLocaleString("en-US"));
  assert.ok(fidData.profile.username, "live sample should have a username");
  assert.equal(await page.getByTestId("lookup-submit").count(),0);
  await page.getByTestId("lookup-clear").click();
  assert.equal(await page.getByTestId("lookup-input").inputValue(),"");
  assert.equal(await page.getByTestId("activity-graph").count(),0);
  assert.ok(await page.getByTestId("brand-chart").isVisible());
  assert.equal(new URL(page.url()).search,"");
  await page.getByTestId('copy-link').click();
  const resetShare = new URL(await page.evaluate(() => navigator.clipboard.readText()));
  assert.equal(resetShare.pathname, '/');
  assert.equal(resetShare.searchParams.has('user'), false);
  await page.getByTestId("lookup-input").fill('@' + fidData.profile.username);
  const lookup = page.waitForResponse(r => r.url().includes('/api/activity?') && r.status() === 200);
  await page.getByTestId("lookup-submit").click(); await lookup;
  await page.getByTestId("lookup-clear").waitFor();
  await page.getByTestId("year-2025").click();
  await page.waitForFunction(() => document.querySelector('[data-testid="year-2025"]').getAttribute('aria-pressed') === 'true' && !document.querySelector('.is-loading'));
  assert.equal(await page.locator('.heatmap rect').count(), 365);
  await page.getByTestId("copy-link").click();
  const copied = await page.evaluate(() => navigator.clipboard.readText());
  const share = new URL(copied);
  assert.equal(share.pathname, '/share/366713'); assert.equal(share.searchParams.get('period'), '2025');
  assert.match(share.searchParams.get('ts'), /^\d{13}$/);
  await page.getByTestId("share-x").click();
  const x = new URL(await page.evaluate(() => window.__lastShare));
  assert.match(x.searchParams.get('text'), /^@.+ has [\d,]+ captured Farcaster actions/);assert.match(x.searchParams.get('text'), /current activity streak is [\d,]+ days?(?: and their longest streak was [\d,]+ days?)?\.\n\nHow about you\?/);
  assert.ok(x.searchParams.get('text').endsWith('\n\nHow about you?\n\nfaralytics - created by @NikolaiLeb with @viniapp_xyz'));
  assert.equal(x.hostname, 'x.com'); const xShare = new URL(x.searchParams.get('url'));
  assert.equal(xShare.pathname, share.pathname);
  assert.equal(xShare.searchParams.get('period'), share.searchParams.get('period'));
  assert.notEqual(xShare.searchParams.get('ts'), share.searchParams.get('ts'));
  await page.getByTestId("share-farcaster").click();
  const fc = new URL(await page.evaluate(() => window.__lastShare));
  assert.ok(fc.searchParams.get('text').endsWith('\n\nHow about you?\n\nfaralytics - created by @nikolaii.eth with @viniapp'));
  assert.equal(fc.hostname, 'farcaster.xyz'); const fcShare = new URL(fc.searchParams.get('embeds[]'));
  assert.equal(fcShare.pathname, share.pathname);
  assert.equal(fcShare.searchParams.get('period'), share.searchParams.get('period'));
  assert.notEqual(fcShare.searchParams.get('ts'), xShare.searchParams.get('ts'));
  await page.getByTestId('share-farcaster-bottom').click();
  const bottomFc = new URL(await page.evaluate(() => window.__lastShare));
  assert.equal(bottomFc.hostname,'farcaster.xyz');
  assert.equal(new URL(bottomFc.searchParams.get('embeds[]')).pathname,share.pathname);
  await page.getByTestId('share-x-bottom').click();
  const bottomX = new URL(await page.evaluate(() => window.__lastShare));
  assert.equal(bottomX.hostname,'x.com');
  assert.equal(new URL(bottomX.searchParams.get('url')).searchParams.get('period'),'2025');
  await page.getByTestId('copy-link-bottom').click();
  const bottomCopied = new URL(await page.evaluate(() => navigator.clipboard.readText()));
  assert.equal(bottomCopied.pathname,share.pathname);
  assert.equal(bottomCopied.searchParams.get('period'),'2025');
  await page.screenshot({ path: 'artifacts/desktop.png', fullPage: true });
  const localShare = new URL(copied);
  const testedOrigin = new URL(page.url());
  localShare.host = testedOrigin.host;
  localShare.protocol = testedOrigin.protocol;
  const response = await page.goto(localShare.toString(), { waitUntil: 'networkidle' });
  assert.equal(response.status(), 200);
  assert.equal(await page.locator('.heatmap rect').count(), 365);
  const meta = await page.locator('meta[name="fc:miniapp"]').getAttribute('content');
  assert.equal(JSON.parse(meta).button.action.url, copied);
  assert.equal(JSON.parse(meta).button.title, "Check My Faralytics");
  assert.equal(new URL(JSON.parse(meta).imageUrl).searchParams.get('ts'), share.searchParams.get('ts'));
  for (const selector of ['meta[name="twitter:image"]', 'meta[property="og:image"]']) {
    assert.equal(new URL(await page.locator(selector).getAttribute('content')).searchParams.get('ts'), share.searchParams.get('ts'));
  }
  assert.equal(await page.locator('link[rel="canonical"]').getAttribute('href'), copied);
  assert.ok((await page.locator('meta[name="twitter:image"]').getAttribute('content')).includes('/api/og/x.png'));
  assert.ok((await page.locator('meta[property="og:image"]').getAttribute('content')).includes('/api/og/farcaster.png'));
  await page.getByTestId('year-2024').click();
  await page.waitForFunction(() => !document.querySelector('.is-loading'));
  assert.equal(await page.locator('.heatmap rect').count(), 366);
  await page.locator('.heatmap rect[role="button"]').first().focus();
  await page.keyboard.press('Enter');
  assert.ok((await page.locator('.day-detail').innerText()).includes('2024'));
  for(const width of [360,375,390,768,1280]) {
    await page.setViewportSize({width,height:900});
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `no page overflow at ${width}`);
    for(const id of ['lookup-input','lookup-clear','share-x','share-farcaster']) {
      const box = await page.getByTestId(id).boundingBox();
      assert.ok(box && box.x >= 0 && box.x+box.width <= width + 1, `${id} fits at ${width}`);
    }
    if(width===375) await page.screenshot({path:'artifacts/mobile.png', fullPage:true});
  }
  await page.getByTestId('lookup-input').fill('not_a_valid_username');
  await page.getByTestId('lookup-submit').click();
  await page.getByTestId('lookup-error').waitFor();
  assert.ok((await page.getByTestId('lookup-error').innerText()).includes('valid'));
  await page.getByTestId('lookup-input').fill('18446744073709551615');
  await page.getByTestId('lookup-submit').click();
  await page.getByTestId('empty-activity').waitFor();
  assert.equal(await page.getByTestId('activity-total').innerText(), '0');
  assert.equal(await page.locator('.heatmap rect').count(), 365);
  assert.deepEqual(errors, []);
  fs.writeFileSync('artifacts/browser-checks.json', JSON.stringify({passed:true, checks:['FID and username lookup','365-day range','calendar year switching and leap year','copy link','Farcaster and X composer URLs','per-user share HTML and metadata','keyboard day details','responsive 360/375/390/768/1280','invalid username error','empty account','no runtime errors']},null,2));
  console.log('Browser checks passed: lookup, years, shares, metadata, keyboard, responsive layout, validation and empty state.');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
